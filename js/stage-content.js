<ul>
<li><strong>Kỹ thuật prompt engineering được sử dụng:</strong> Constraint Prompting (giới hạn độ dài), Structured Prompting (quy định cấu trúc), Instruction Prompting (đưa yêu cầu cụ thể).</li>
<li><strong>Ưu điểm:</strong> nội dung đầy đủ hơn; có định hướng rõ ràng, kết quả logic hơn prompt cơ bản.</li>
<li><strong>Hạn chế:</strong> AI vẫn có thể chưa xác định được đâu là nội dung trọng tâm nhất, mức độ học thuật chưa thật sự ổn định.</li>
</ul>
